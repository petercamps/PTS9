## An instance of the SkirtTestSuite class represents a suite of SKIRT test cases, stored as
# a nested structure of files and directories according to a specific layout, and provides facilities to
# perform the tests, verify the results, and prepare a summary test report.
#
# A test suite consists of a set of independent test cases (i.e. test cases can be executed in arbitrary order)
#
# Each test case in a test suite is defined by a collection of files and directories as follows:
#  - a directory with arbitrary name containing all test case files and directories, called the "case directory";
#    a test suite is named after this directory
#  - immediately inside the case directory there is:
#    - exactly one \em ski file with an arbitrary name (with the \c .ski filename extension) specifying the simulation
#      to be performed for the test case
#    - a directory named \c in containing the input files for the simulation, if any
#    - optionally, a text file named \c command_line.txt specifying the value of one or more SKIRT command line
#      options for the test case, one option per line, with the option and its value separated by white space. The
#      first line starting with \c -i specifies the input path (the default is \c in), and the first line starting with
#      \c -o specifies the output path (the default is \c out), both relative to the case directory. Any other lines
#      are ignored. This allows a test case to obtain its input from an HDF5 file in the \c in directory, for example
#      through a line reading <tt>-i in/data.hdf5:suite</tt>, or to write its output to an HDF5 file in the \c out
#      directory, through a line reading <tt>-o out/data.hdf5:suite</tt>. Because the results of a test case are
#      verified by comparing the files in the \c out directory with those in the \c ref directory, the output path
#      must refer to the \c out directory or to an HDF5 file in that directory. In the latter case, the bundles that
#      the test case writes are first converted to regular files in the \c out directory, and these files are
#      compared according to the type of their bundle, as described for the findDifferences() function.
#    - a directory named \c ref containing the reference files for the test, i.e. a copy of the output files
#      generated by a correct simulation run
#    - a directory named \c out to receive the actual output files when the test is performed; the contents
#      of this directory are automatically removed and recreated when running the test case
#    - everything else is ignored, as long as there are no additional files with a \c .ski filename extension
#
# A test suite is defined by a collection of files and directories as follows:
#  - a directory directly or indirectly containing all test cases, called the "suite directory";
#    a test suite is named after this directory
#  - each ski file directly or indirectly contained in the suite directory defines a test case that
#    must adhere to the description above (no other ski files in the same directory, special directories
#    next to the \em ski file, etc.)
#
# For example, a test suite may be structured with nested sub-suites as follows (where each \c CaseN directory
# contains a ski file plus \c ref, \c in, and \c out directories):
#
# \verbatim
# SKIRT Tests
#   SPH simulations
#       Case1
#       Case2
#   Geometries
#     Radial
#         Case1
#         Case2
#     Cylindrical
#         Case1
#         Case2
#         Case3
#     Full 3D
#         Case1
#         Case2
#   Instruments
# \endverbatim
#
# It is also allowed to nest test cases inside another test case, but this is not recommended.
#
class SkirtTestSuite:

    ## The first argument accepted by the constructor indicates the selection of functional tests to be performed:
    #  - "." (a single period): perform all test cases in the standard suite.
    #  - "testcase" (the name of a test case directory): perform all test cases with that name.
    #  - "subsuite" (the name of an intermediate directory in the hierarchy): perform the test cases in all sub-suites
    #    with that name.
    #  - "parentsubsuite/testcase" or "parentsubsuite/subsuite": perform the indicated test case(s) or sub-suite(s)
    #    that reside immediately inside the indicated parent sub-suite; this can disambiguate items with the same name.
    #
    # In addition, the constructor accepts an optional argument specifying the path of the directory containing the
    # complete functional test suite. If specified, the path is interpreted as described for the pts.utils.absPath()
    # function. If omitted, the default path is pts.utils.projectParentPath()/"Functional10".
    def __init__(self, subSuite=".", *, suitePath=None):

        # set the top-level suite path and remember the skirt path
        self._suitePath = ut.absPath(suitePath) if suitePath is not None else ut.projectParentPath()/"Functional10"

        # find all matching sub-suite paths
        if subSuite is None or subSuite == "" or "." in subSuite:
            subSuitePaths = [ self._suitePath ]
        else:
            subSuitePaths = self._suitePath.rglob(subSuite)

        # find all valid test cases in any of the sub-suite paths and remember the paths to the corresponding ski files
        skiPathSet = set()
        for subSuitePath in subSuitePaths:
            for skiPath in subSuitePath.rglob("[!.]*.ski"):
                if len(list(skiPath.parent.glob("[!.]*.ski"))) == 1:
                    skiPathSet.add(skiPath)
        self._skiPaths = sorted(skiPathSet)

        # abort if there are no valid test cases
        if len(self._skiPaths) == 0:
            raise ut.UserError("No valid test cases found for sub-suite specification: '{}'".format(subSuite))

    ## This function returns the number of test cases in this test suite
    def size(self):
        return len(self._skiPaths)

    ## This function returns a list of the paths to the ski files for the test cases in this test suite
    def skiPaths(self):
        return self._skiPaths

    ## This function returns the values to be passed to the \c -i and \c -o options of SKIRT for the test case with
    # the specified ski file path, as a tuple of two strings holding paths relative to the case directory. If the case
    # directory contains a \c command_line.txt file, the value for each option is taken from the first line in that
    # file that starts with the option, followed by white space and the value. Otherwise, or if there is no such line,
    # the values default to the \c in and \c out directories.
    def _commandLineOptions(self, skipath):
        options = { "-i": "in", "-o": "out" }
        optionsFile = skipath.parent / "command_line.txt"
        if optionsFile.is_file():
            found = set()
            for line in optionsFile.read_text().splitlines():
                tokens = line.split(None, 1)
                if len(tokens) == 2 and tokens[0] in options and tokens[0] not in found:
                    options[tokens[0]] = tokens[1].strip()
                    found.add(tokens[0])
        return options["-i"], options["-o"]

    ## This function returns the location of the HDF5 file, and of the suite within that file, to which the test case
    # with the specified ski file path writes its output, as a string holding an absolute path in the form
    # <tt>\<dir\>/\<hdf\>:\<suite\></tt>, or None if the output path of the test case does not name an HDF5 file.
    # As in SKIRT, the output path names an HDF5 file if it is not an existing directory and it includes the \c .hdf5
    # filename extension followed by a colon, or ends with that extension.
    def _outputLocation(self, skipath):
        outpath = self._commandLineOptions(skipath)[1]
        location = str(skipath.parent / outpath)
        if (skipath.parent / outpath).is_dir() or (".hdf5:" not in location and not location.endswith(".hdf5")):
            return None
        return location

    ## This function prepares the contents of all test case directories in the sub-suite for performing the tests.
    # Specifically, it creates \c in, \c out and \c ref directories next to the ski file, if they don't exist,
    # and it removes all files from the \c out directory (without touching any of its subdirectories, which should
    # not be present anyway).
    def clean(self):
        # loop over all ski files in the sub-suite
        for skipath in self._skiPaths:

            # create test case subdirectories as needed
            casedir = skipath.parent
            (casedir/"in").mkdir(exist_ok=True)
            (casedir/"out").mkdir(exist_ok=True)
            (casedir/"ref").mkdir(exist_ok=True)

            # remove files from the "out" subdirectory
            for path in (casedir/"out").glob("*"):
                if path.is_file(): path.unlink()

    ## This function "endorses" the current output of all test case directories in the sub-suite by
    # replacing the contents of the "ref" directory by the contents of the "out" directory.
    # \note This function destroys the current reference output for test cases; USE WITH CARE!
    def endorse(self):
        # loop over all ski files in the sub-suite
        for skipath in self._skiPaths:
            casedir = skipath.parent

            # remove the contents of the ref directory
            for path in (casedir/"ref").glob("*"):
                if path.is_file(): path.unlink()

            # move the contents of the out directory to the ref directory, except for hidden files and test reports
            for path in (casedir/"out").glob("[!._]*"):
                if path.is_file():
                    target = casedir/"ref"/path.name
                    path.replace(target)

    ## This function performs all tests in the test suite, verifies the results, and prepares a summary test report.
    # The function accepts two optional arguments:
    #  - \em skirtPath: the path to the skirt executable. If specified, the path is interpreted as described for
    #    the pts.utils.absPath() function. If omitted, the default path is used as described for the constructor
    #    of the pts.simulation.skirt.Skirt class.
    #  - \em visual: a string describing the visualizations to be created for the output of each test case, if any.
    #    If specified, the string is a semicolon-separated list of PTS visualization commands as they would be entered
    #    at the command line, omitting the simulation output path argument (which will be inserted automatically).
    def perform(self, *, skirtPath=None, visual=None):
        # create a SKIRT execution context for each core on the host computer
        numCores = min(24, len(self._skiPaths), max(multiprocessing.cpu_count(), 1))
        skirts = [ sm.Skirt(skirtPath) for core in range(numCores) ]

        # inform the user of the fact that the tests are being initiated
        skirtversion = skirts[0].version()
        skirtpath = skirts[0].path()
        logging.info("Using {}".format(skirtversion))
        logging.info("With path {}".format(skirtpath))
        logging.info("Running on {} for {}".format(ut.hostname(), ut.username()))
        logging.info("Performing {} functional test case(s) in {} parallel processes..." \
                     .format(len(self._skiPaths), numCores))

        # prepare the test case directories
        self.clean()

        # initialize statistics
        statistics = { }

        # initialize the list of remaining test cases and the list of simulations being processed
        cases = self._skiPaths.copy()
        sims = [ ]
        numTotal = len(cases)
        numDone = 0

        # main "event loop" runs as long as there are test cases to be processed
        while True:
            # start new skirt executions where possible, and remove the started test cases from the list
            for skirt in skirts:
                if not skirt.isRunning() and len(cases)>0:
                    skipath = cases.pop(0)
                    inpath, outpath = self._commandLineOptions(skipath)
                    sims.append(skirt.execute(skiFilePath=skipath, skiRelative=True,
                                              inDirPath=inpath, outDirPath=outpath,
                                              numProcesses=1, numThreadsPerProcess=1, console='silent', wait=False))

            # if a simulation is ready, report on it and remove it from the list
            # we only report on one simulation at a time to ensure that new skirt executions are launched frequently
            oldNumDone = numDone
            for simindex, sim in enumerate(sims):
                if not sim.isRunning():
                    numDone += 1
                    status = reportTestCase(sim, self._outputLocation(sim.skiFilePath()))
                    if not status in statistics: statistics[status] = 0
                    statistics[status] += 1
                    testname = sim.skiFilePath().relative_to(self._suitePath).parent
                    level = logging.INFO if status == "Succeeded" else logging.WARNING
                    logging.log(level, "{:3d} -- {}: {}".format(numDone, testname, status))
                    del sims[simindex]

                    # create visualizations if requested
                    if visual is not None and status != "Crashed":
                        for command in visual.split(";"):
                            arguments = command.split()
                            if len(arguments)>0:
                                arguments.insert(1, str(sim.outDirPath()))
                                pts.do.doWithCommandLineArguments(arguments)
                    break

            if numDone == numTotal:
                break

            # if no simulation was ready, sleep for a while to avoid consuming lots of CPU
            if numDone == oldNumDone:
                time.sleep(1)

        # log test summary
        logging.info("Summary for {} test case(s):".format(numTotal))
        for status in sorted(statistics.keys()):
            level = logging.INFO if status == "Succeeded" else logging.WARNING
            logging.log(level, "  {}: {}".format(status, statistics[status]))

        # create a consolidated test report at the top suite level
        reportdir = self._suitePath / "_testreports"
        reportname = "{}_testreport_{}.txt".format(ut.timestamp(), numTotal)
        reportdir.mkdir(exist_ok=True)
        with open(reportdir / reportname, "wt") as confile:
            # write header and summary
            confile.write("Using {}\n".format(skirtversion))
            confile.write("With path {}\n".format(skirtpath))
            confile.write("Running on {} for {}\n".format(ut.hostname(), ut.username()))
            confile.write("Summary for {} test case(s):\n".format(numTotal))
            for status in sorted(statistics.keys()):
                confile.write("  {}: {}\n".format(status, statistics[status]))
            confile.write("---------------\n")

            # copy reports for all performed test cases
            for skipath in self._skiPaths:
                testname = skipath.relative_to(self._suitePath).parent
                confile.write("{}: ".format(testname))
                with open(skipath.parent/"out"/"_testreport.txt", "rt") as reportfile:
                    for line in reportfile:
                        confile.write(line)

            # write footer
            confile.write("---------------\n")

# -----------------------------------------------------------------

## This function verifies the results for the test case represented by the specified simulation, creates
# a test report in the output directory, and returns an overall status string: "Crashed", "Failed", or "Succeeded".
#
# If the test case writes its output to an HDF5 file, the \em hdf5Location argument specifies the location of that
# file and of the suite within it, as returned by the SkirtTestSuite._outputLocation() function. The function then
# first converts the bundles at that location to regular files in the output directory, and compares the converted
# files according to the type of their bundle, as described for the findDifferences() function. A file that the test
# case wrote both as a regular file and as a bundle, or a bundle that cannot be converted, causes the test case to
# fail, except for a column text file of which the bundle holds the same information as the regular file: SKIRT
# writes some column text files, such as the iteration history, incrementally as regular files and also stores them
# as bundles at the end of the run, leaving the regular file in place.
def reportTestCase(sim, hdf5Location=None):
    duplicates = []
    unconverted = []
    converted = {}

    # if the simulation has not properly finished by now, it must have crashed
    if sim.status() != "Finished":
        status = "Crashed"
    else:
        # convert the output bundles, if any
        if hdf5Location is not None:
            duplicates, unconverted, converted = _convertOutputBundles(hdf5Location, sim.outDirPath())

        # verify the results
        extra, missing, differing = findDifferences(sim, converted)
        if len(duplicates) + len(unconverted) + len(extra) + len(missing) + len(differing) > 0:
            status = "Failed"
        else:
            status = "Succeeded"

    # create the report file
    with open(sim.outDirPath() / "_testreport.txt", "wt") as reportfile:
        reportfile.write(status + "\n")
        if status == "Failed":
            if len(duplicates)>0:
                reportfile.write("  Files written both as a regular file and as a bundle:\n")
                for name in duplicates:
                    reportfile.write("    {}\n".format(name))
            if len(unconverted)>0:
                reportfile.write("  Bundles that cannot be converted to a regular file:\n")
                for name in unconverted:
                    reportfile.write("    {}\n".format(name))
            if len(extra)>0:
                reportfile.write("  Extra files:\n")
                for name in extra:
                    reportfile.write("    {}\n".format(name))
            if len(missing)>0:
                reportfile.write("  Missing files:\n")
                for name in missing:
                    reportfile.write("    {}\n".format(name))
            if len(differing)>0:
                reportfile.write("  Differing files:\n")
                for name in differing:
                    statistics = getDifferenceStatistics(sim, name, converted.get(name))
                    reportfile.write("    {:<40s} -- {}\n".format(name, statistics))
    return status

## This function looks for relevant differences between the contents of the output and reference directories of the
# test case represented by the specified simulation. The function returns three lists of file names, which should all
# be empty for the test case to be successful:
#   - a list of extra files: files present in the output directory but not in the reference directory.
#   - a list of missing files: files present in the reference directory but not in the output directory.
#   - a list of differing files: files present in both directories but which have a different contents.
#
# The function only handles files of the following types:
#   - "*.dat": the contents of these files must be identical.
#   - "*.fits": the contents of these files must be identical except for the information in one header line
#               (allowing a different time stamp)
#
# A file that was converted from a bundle written by the test case is listed in the optional \em converted argument,
# a dictionary that maps the name of the file to the type of its bundle, as returned by the
# pts.hdf5.inferBundleType() function. Because the conversion does not reproduce the formatting of the file that
# SKIRT would have written, such a file is instead compared according to the type of its bundle: a text column file
# as described for the _areEqualColumnFiles() function, a spatial grid plot file as described for the
# _areEqualGridPlotFiles() function, and a FITS file as described for the _areEqualFitsContents() function. A file of
# another type must be identical.
#
# Any other files are ignored. Specifically, this means that the following file types are \em not compared:
#   - the SKIRT log file ("*.log")
#   - the parameter file generated by SKIRT ("*_parameters.xml")
#   - visualization files generated by PTS ("*.pdf", "*.png")
def findDifferences(sim, converted=None):
    converted = converted if converted else {}

    # get the output and reference paths
    outpath = sim.outDirPath()
    refpath = outpath.parent / "ref"

    # ensure that neither has any subdirectories
    if len([ path for path in outpath.glob("*") if path.is_dir() ]) > 0:
            raise ValueError("Test case 'out' directory has subdirectories")
    if len([ path for path in refpath.glob("*") if path.is_dir() ]) > 0:
            raise ValueError("Test case 'ref' directory has subdirectories")

    # create list of extra, missing and common files of types ".dat" and ".fits"
    dircomp = filecmp.dircmp(outpath, refpath)
    extra = [ name for name in dircomp.left_only if name.endswith((".dat",".fits")) ]
    missing = [ name for name in dircomp.right_only if name.endswith((".dat",".fits")) ]
    common = [ name for name in dircomp.common if name.endswith((".dat",".fits")) ]

    # compare common files, focusing on those that aren't trivially equal.
    matches, mismatches, errors = filecmp.cmpfiles(outpath, refpath, common, shallow=False)
    def isDifferent(name):
        bundleType = converted.get(name)
        if bundleType == "columns": return not _areEqualColumnFiles(outpath/name, refpath/name)
        if bundleType == "gridplot": return not _areEqualGridPlotFiles(outpath/name, refpath/name)
        if bundleType == "fits": return not _areEqualFitsContents(outpath/name, refpath/name)
        if bundleType is None and name.endswith(".fits"): return not _areEqualFitsFiles(outpath/name, refpath/name)
        return True
    differing = [ name for name in mismatches + errors if isDifferent(name) ]

    # return the lists of extra, missing, and differing files
    return extra, missing, differing

## This function returns a string describing some basic statistics on the difference between the reference and
# output files of the specified name in the specified simulation. It supports text columns files and FITS files.
# Essentially, the string shows the number of nonzero values that don't match, that differ by more than 10
# percent, and that differ by more than 50% between the files. If the output file was converted from a bundle, the
# optional \em bundleType argument specifies the type of that bundle, as for the findDifferences() function; the
# values are then rounded to the precision that SKIRT uses for that type of file before they are compared.
def getDifferenceStatistics(sim, name, bundleType=None):

    # get the file paths
    refpath = sim.outDirPath().parent / "ref" / name
    outpath = sim.outDirPath() / name

    # load data
    if name.endswith(".dat"):
        try:
            ref = np.loadtxt(refpath)
            out = np.loadtxt(outpath)
        except ValueError:
            return "text file has non-numeric contents"
        if bundleType in ("columns", "gridplot"):
            digits = 9 if bundleType == "columns" else 8
            ref = _rounded(ref, digits)
            out = _rounded(out, digits)
    elif name.endswith(".fits"):
        ref = fits.getdata(refpath)
        out = fits.getdata(outpath)
        if bundleType == "fits":
            ref = np.asarray(ref, dtype=np.float32)
            out = np.asarray(out, dtype=np.float32)
    else:
        return "unsupported file format"

    # verify shape
    if ref.shape != out.shape:
        if len(ref.flatten()) == len(out.flatten()) and np.all(ref.flatten() == out.flatten()):
            return "data shape differs with identical contents"
        else:
            return "data shape and contents differ"

    # get statistics
    with warnings.catch_warnings():
        warnings.filterwarnings('ignore', message="invalid value encountered in")
        nonzero = ref != 0
        numNonzero = np.count_nonzero(nonzero)
        relDiff = np.abs((out[nonzero] - ref[nonzero]) / ref[nonzero])
        numDiff = np.count_nonzero(relDiff > 0)
        numDiff10 = np.count_nonzero(relDiff > 0.10)
        numDiff50 = np.count_nonzero(relDiff > 0.50)

    # format statistics into a string
    return "{:6d} ({:6.2f}%) >0   {:6d} ({:6.2f}%) >10   {:6d} ({:6.2f}%) >50" \
                    .format(numDiff, 100*numDiff/numNonzero if numNonzero>0 else 100 if numDiff>0 else 0,
                            numDiff10, 100*numDiff10/numNonzero if numNonzero>0 else 100 if numDiff10>0 else 0,
                            numDiff50, 100*numDiff50/numNonzero if numNonzero>0 else 100 if numDiff50>0 else 0)

## This helper function converts the bundles at the specified location in an HDF5 file, written by a test case, to
# regular files in the specified output directory. It returns two lists and a dictionary: the names of the bundles
# for which the test case also wrote a regular file, which is not replaced; the names of the bundles that cannot be
# converted; and a dictionary that maps the name of each converted file to the type of its bundle, as returned by the
# pts.hdf5.inferBundleType() function. Bundles with a type that is not recognized are ignored, and so are the bundles
# for the log file and the parameter file (with a name ending in \c _log.txt or \c _parameters.xml), because SKIRT
# keeps these files as regular files in the output directory next to their bundles. Similarly, a column text file
# bundle for which the test case also wrote a regular file is not counted as a duplicate if it holds the same
# information as that file (see the _areEqualColumnFiles() function), because SKIRT keeps the regular file in place
# for the column text files that it writes incrementally and stores as a bundle at the end. The function does nothing
# if the HDF5 file does not exist, because a test case that writes no bundles does not create it. The informational
# messages logged by the conversion functions are suppressed.
def _convertOutputBundles(location, outdir):
    import pts.hdf5 as hdf

    duplicates = []
    unconverted = []
    converted = {}
    filePath, suite = hdf.splitBundlePath(location)
    if ut.absPath(filePath).is_file():
        logging.disable(logging.INFO)
        try:
            for bundlePath in hdf.findBundles(location):
                name = hdf.splitBundlePath(bundlePath)[1].rpartition("/")[2]
                if name.endswith(("_log.txt", "_parameters.xml")): continue
                try:
                    bundleType = hdf.inferBundleType(bundlePath)
                    if bundleType is not None:
                        if (outdir / name).exists():
                            if not (bundleType == "columns" and _isCopyOfColumnFile(bundlePath, outdir / name)):
                                duplicates.append(name)
                        else:
                            hdf.convertBundle(bundlePath, outdir)
                            converted[name] = bundleType
                except (ut.UserError, OSError):
                    unconverted.append(name)
        except ut.UserError:
            unconverted.append(suite if suite else filePath)
        finally:
            logging.disable(logging.NOTSET)
    return duplicates, unconverted, converted

## This helper function returns True if the specified column text file bundle holds the same information as the
# specified regular column text file, as described for the _areEqualColumnFiles() function, and False otherwise. It
# converts the bundle to a regular file in a temporary directory for the comparison.
def _isCopyOfColumnFile(bundlePath, filePath):
    import tempfile
    import pts.hdf5 as hdf
    with tempfile.TemporaryDirectory() as tmpdir:
        convertedPath = hdf.convertBundle(bundlePath, tmpdir, fileName=filePath.name)
        return _areEqualColumnFiles(convertedPath, filePath)

## This helper function returns True if the specified column text files hold the same information when their numbers
# are rounded to nine significant digits, the precision of the column text files written by SKIRT, and False
# otherwise. Both files must have the same column information lines, in the same order, and the same other header
# lines, in the same order, but the latter may precede or follow the column information lines. White space within a
# header line is not significant. The files must have the same number of data lines with the same number of values,
# and corresponding values must be equal after formatting each of them in exponential notation with nine digits
# after the decimal point. As a result, a value written by SKIRT in that notation or as an integer compares equal to
# the same value in a file converted from a bundle, in which numbers are written with the smallest number of digits
# that represents them exactly.
def _areEqualColumnFiles(filePath1, filePath2):
    def parse(filePath):
        columns = []
        comments = []
        rows = []
        with open(filePath, 'rt') as infile:
            for line in infile:
                line = line.strip()
                if not line: continue
                if line.startswith("#"):
                    text = " ".join(line[1:].split())
                    if _columnInfoSyntax.fullmatch(text): columns.append(text)
                    else: comments.append(text)
                else:
                    rows.append([ "{:.9e}".format(float(token)) for token in line.split() ])
        return columns, comments, rows

    try:
        return parse(filePath1) == parse(filePath2)
    except (ValueError, OSError, UnicodeDecodeError):
        return False

## The syntax of a column information line in a column text file, after removing the hash character
_columnInfoSyntax = re.compile(r"column\s*\d+\s*:.*", re.IGNORECASE)

## This helper function returns True if the specified spatial grid plot files hold the same polylines when their
# coordinates are rounded to eight significant digits, the precision of the spatial grid plot files written by SKIRT,
# and False otherwise. In these files, the consecutive nonempty lines of a polyline each hold the coordinates of a
# point, and an empty line ends a polyline. Both files must have the same number of polylines, each with the same
# number of points with the same number of coordinates, and corresponding coordinates must be equal after formatting
# each of them in exponential notation with seven digits after the decimal point. As a result, a coordinate written by
# SKIRT compares equal to the same coordinate in a file converted from a bundle, in which numbers are written with
# the smallest number of digits that represents them exactly.
def _areEqualGridPlotFiles(filePath1, filePath2):
    def parse(filePath):
        polylines = []
        current = []
        with open(filePath, 'rt') as infile:
            for line in infile:
                tokens = line.split()
                if tokens:
                    current.append([ "{:.7e}".format(float(token)) for token in tokens ])
                elif current:
                    polylines.append(current)
                    current = []
        if current: polylines.append(current)
        return polylines

    try:
        return parse(filePath1) == parse(filePath2)
    except (ValueError, OSError, UnicodeDecodeError):
        return False

## This helper function returns True if the specified FITS files hold the same frame or data cube with the same
# metadata, as far as SKIRT records it in a FITS file, and False otherwise. The data in the primary header-data unit
# must have the same shape, and the same values after converting them to 32-bit floating point numbers, the precision
# of the FITS files written by SKIRT. This allows comparing a file converted from a bundle, which may hold 64-bit
# values, with a reference file. The units of the data and of the axes (the BUNIT, CUNIT1, CUNIT2, and CUNIT3 cards)
# must be equal, and so must the distance unit (DISTUNIT). The grid points of each axis, listed in a table extension
# or described by the CRPIX, CRVAL, and CDELT cards, must be equal to within a relative tolerance of 1e-8 with respect
# to the largest absolute grid point of the axis, which allows for the ten significant digits with which SKIRT writes
# these values. The observer information (the CROTA1, CROTA2, CROTA3, REDSHIFT, DISTLUMI, and DISTANGD cards) must
# be equal to within the same relative tolerance. Other header cards, such as the creation date, are ignored.
def _areEqualFitsContents(filePath1, filePath2):
    tolerance = 1e-8

    def parse(filePath):
        with fits.open(filePath) as hdul:
            header = hdul[0].header
            data = hdul[0].data
            pixels = None if data is None else np.asarray(data, dtype=np.float32)
            strings = { card: str(header[card]).strip() if card in header else None
                        for card in ("BUNIT", "CUNIT1", "CUNIT2", "CUNIT3", "DISTUNIT") }
            numbers = { card: float(header[card]) if card in header else None
                        for card in ("CROTA1", "CROTA2", "CROTA3", "REDSHIFT", "DISTLUMI", "DISTANGD") }
            axes = []
            if data is not None:
                sizes = (data.shape[-1], data.shape[-2], data.shape[0] if data.ndim == 3 else 0)
                for number, size in enumerate(sizes, 1):
                    axes.append(_fitsAxisGrid(hdul, number, size) if size else None)
        return pixels, strings, numbers, axes

    def areClose(value1, value2):
        if value1 is None or value2 is None: return value1 is None and value2 is None
        return abs(value1 - value2) <= tolerance * max(abs(value1), abs(value2))

    try:
        pixels1, strings1, numbers1, axes1 = parse(filePath1)
        pixels2, strings2, numbers2, axes2 = parse(filePath2)
        if (pixels1 is None) != (pixels2 is None): return False
        if pixels1 is not None and (pixels1.shape != pixels2.shape or
                                    not np.array_equal(pixels1, pixels2, equal_nan=True)): return False
        if strings1 != strings2: return False
        if not all(areClose(numbers1[card], numbers2[card]) for card in numbers1): return False
        for grid1, grid2 in zip(axes1, axes2):
            if grid1 is None or grid2 is None:
                if grid1 is not None or grid2 is not None: return False
            elif len(grid1) != len(grid2):
                return False
            elif len(grid1) > 0:
                scale = max(np.max(np.abs(grid1)), np.max(np.abs(grid2)))
                if not np.all(np.abs(grid1 - grid2) <= tolerance * scale): return False
        return True
    except (OSError, ValueError, KeyError, TypeError, IndexError):
        return False

## This helper function returns the grid points of the axis with the specified one-based number in the specified
# opened FITS file, as a one-dimensional array of 64-bit floating point numbers, or None if the file does not
# describe them. The grid points are taken from the table extension for that axis ("X-axis coordinate values", and
# so on), if present, or else from the CRPIX, CRVAL, and CDELT cards for a regular linear grid with the specified
# number of points.
def _fitsAxisGrid(hdul, number, size):
    extension = "{}-axis coordinate values".format("XYZ"[number-1])
    if extension in hdul:
        return np.asarray(hdul[extension].data["GRID_POINTS"], dtype=np.float64)
    header = hdul[0].header
    cards = [ "{}{}".format(card, number) for card in ("CRPIX", "CRVAL", "CDELT") ]
    if all(card in header for card in cards):
        crpix, crval, cdelt = [ float(header[card]) for card in cards ]
        return crval + cdelt * (np.arange(size) + 1 - crpix)
    return None

## This helper function returns a copy of the specified array with each value rounded to the specified number of
# significant digits.
def _rounded(values, digits):
    return np.array([ float("{:.{}e}".format(value, digits - 1)) for value in values.flat ]).reshape(values.shape)

## This helper function returns True if the specified FITS files are equal except for the information
#  in a single header record, and False otherwise.
def _areEqualFitsFiles(filePath1, filePath2):
    return _areEqualLists(_readBlocks(filePath1), _readBlocks(filePath2), 1)

## This helper function returns True if the specified lists are equal except for the contents of
#  a number of items not larger than \em allowedDiffs, and False otherwise.
def _areEqualLists(list1, list2, allowedDiffs):

    # the lists must have the same length, which must be at least 2 (to avoid everything being read into 1 line)
    length = len(list1)
    if length < 2 or length != len(list2): return False

    # compare the lists item by item
    diffs = 0
    for index in range(length):
        if list1[index] != list2[index]:
            # verify against allowed number of differences
            diffs += 1
            if diffs > allowedDiffs: return False

    # no relevant differences
    return True

## This helper function reads blocks of 80 bytes from the specified binary file into a list of bytes objects,
# and returns the list.
def _readBlocks(filepath):
    result = []
    with open(filepath, 'rb') as f:
        while True:
            block = f.read(80)
            if len(block) == 0: break
            result.append(block)
    return result

